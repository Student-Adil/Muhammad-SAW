const slide = document.querySelector("#slide");
const pageDots = document.querySelector("#pageDots");
const progressFill = document.querySelector("#progressFill");
const currentPageLabel = document.querySelector("#currentPageLabel");
const pageChip = document.querySelector("#pageChip");
const slideKicker = document.querySelector("#slideKicker");
const sectionLabel = document.querySelector("#sectionLabel");
const slideTitle = document.querySelector("#slideTitle");
const bodyContent = document.querySelector("#bodyContent");
const symbolIcon = document.querySelector("#symbolIcon");
const miniTimeline = document.querySelector("#miniTimeline");
const pageTitleStrip = document.querySelector("#pageTitleStrip");
const prevBtn = document.querySelector("#prevBtn");
const nextBtn = document.querySelector("#nextBtn");
const coverBtn = document.querySelector("#coverBtn");

let activePage = 0;

function renderDots() {
  pageDots.innerHTML = pages
    .map(
      (page, index) => `
        <button class="dot-button" type="button" data-page="${index}" aria-label="Open ${page.label}">
          <span>${index === 0 ? "C" : index}</span>
        </button>
      `
    )
    .join("");

  pageDots.addEventListener("click", (event) => {
    const button = event.target.closest("[data-page]");
    if (button) setPage(Number(button.dataset.page));
  });
}

function renderTimeline() {
  miniTimeline.innerHTML = pages
    .slice(1)
    .map(
      (page, index) => `
        <button class="timeline-node" type="button" data-page="${index + 1}">
          <span>${page.year}</span>
        </button>
      `
    )
    .join("");

  miniTimeline.addEventListener("click", (event) => {
    const button = event.target.closest("[data-page]");
    if (button) setPage(Number(button.dataset.page));
  });
}

function renderPageTitles() {
  pageTitleStrip.innerHTML = pages
    .map((page, index) => `<button type="button" data-page="${index}">${page.label}</button>`)
    .join("");

  pageTitleStrip.addEventListener("click", (event) => {
    const button = event.target.closest("[data-page]");
    if (button) setPage(Number(button.dataset.page));
  });
}

function setPage(index) {
  activePage = Math.min(Math.max(index, 0), pages.length - 1);
  const page = pages[activePage];

  document.documentElement.style.setProperty("--accent", page.accent);
  slide.style.setProperty("--accent", page.accent);
  slide.dataset.page = String(activePage);
  currentPageLabel.textContent = page.label;
  pageChip.textContent = page.label;
  slideKicker.textContent = page.kicker;
  sectionLabel.textContent = page.section;
  slideTitle.textContent = page.title;
  symbolIcon.textContent = page.icon;
  progressFill.style.width = `${((activePage + 1) / pages.length) * 100}%`;

  bodyContent.innerHTML = `
    ${page.paragraphs.map((paragraph) => `<p>${paragraph}</p>`).join("")}
    <div class="highlight-grid">
      ${page.highlights.map((item) => `<span>${item}</span>`).join("")}
    </div>
  `;

  document.querySelectorAll("[data-page]").forEach((button) => {
    const selected = Number(button.dataset.page) === activePage;
    button.classList.toggle("is-active", selected);
    button.setAttribute("aria-current", selected ? "page" : "false");
  });

  prevBtn.disabled = activePage === 0;
  nextBtn.disabled = activePage === pages.length - 1;
}

prevBtn.addEventListener("click", () => setPage(activePage - 1));
nextBtn.addEventListener("click", () => setPage(activePage + 1));
coverBtn.addEventListener("click", () => setPage(0));

document.addEventListener("keydown", (event) => {
  if (event.key === "ArrowRight") setPage(activePage + 1);
  if (event.key === "ArrowLeft") setPage(activePage - 1);
});

renderDots();
renderTimeline();
renderPageTitles();
setPage(0);
